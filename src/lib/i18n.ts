const DICTS: Record<Lang, Record<MsgKey, string>> = { es, en };

export function getLang(): Lang {
  if (typeof window === "undefined") return DEFAULT_LANG;
  try {
    const v = window.localStorage.getItem(KEY);
    return v === "en" || v === "es" ? v : DEFAULT_LANG;
  } catch {
    return DEFAULT_LANG;
  }
}

export function setLang(lang: Lang): void {
  try {
    window.localStorage.setItem(KEY, lang);
  } catch {
    /* ignore */
  }
  document.documentElement.lang = lang;
  window.dispatchEvent(new Event(EVENT));
}

function subscribe(cb: () => void) {
  window.addEventListener(EVENT, cb);
  window.addEventListener("storage", cb);
  return () => {
    window.removeEventListener(EVENT, cb);
    window.removeEventListener("storage", cb);
  };
}

export function translate(lang: Lang, key: MsgKey, vars?: Record<string, string | number>): string {
  let s: string = DICTS[lang][key] ?? es[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export type TFn = (key: MsgKey, vars?: Record<string, string | number>) => string;

/** Current language and a translate function bound to it. */
export function useT(): { t: TFn; lang: Lang } {
  const lang = useSyncExternalStore(subscribe, getLang, () => DEFAULT_LANG);
  const t = useCallback<TFn>((key, vars) => translate(lang, key, vars), [lang]);
  return { t, lang };
}
